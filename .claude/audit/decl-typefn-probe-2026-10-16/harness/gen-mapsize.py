#!/usr/bin/env python3
"""[2026-10-19 M4] where does the class-name bound `K & keyof<Map>` stop fitting the Roblox-sync limits?
  gen-mapsize.py <out-dir> <N...>   (classes = first N of src/FullMaps.luau CreatableMapFull, Part/Frame/TextLabel/Sound/Model forced in)
Per N two files: bound-N (`<K>(name: K & keyof<Map>) -> index<Map, K>`) and nobound-N (`<K>(name: K) -> index<Map, K>`),
each with 5 OK calls and 2 NEG (typo / abstract)."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "../src/FullMaps.luau")).read()
body = src.split("export type CreatableMapFull = {")[1].split("}")[0]
names = re.findall(r"^\t(\w+): \w+,", body, re.M)
must = ["Part", "Frame", "TextLabel", "Sound", "Model"]
rest = [n for n in names if n not in must]
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
for n in map(int, sys.argv[2:]):
    cls = must + rest[: max(0, n - len(must))]
    m = "type Map = { " + ", ".join(f"{c}: {c}" for c in cls) + " }"
    for kind, sig in (("bound", "<K>(name: K & keyof<Map>) -> index<Map, K>"), ("nobound", "<K>(name: K) -> index<Map, K>")):
        L = ["--!strict", f"-- [2026-10-19 M4] generated by harness/gen-mapsize.py — {len(cls)} classes, {kind}", m,
             f"local E = (nil :: any) :: {sig}"]
        for i, c in enumerate(must):
            L.append(f'local ok{i}: {c} = E "{c}"')
        L.append('local bad1 = E "Prt" -- NEG')
        L.append('local bad2 = E "BasePart" -- NEG')
        L.append("return { ok0, ok1, ok2, ok3, ok4, bad1, bad2 }")
        open(os.path.join(out, f"{kind}-{len(cls):03d}.luau"), "w").write("\n".join(L) + "\n")
