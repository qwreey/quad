#!/usr/bin/env python3
"""Q6 cost probe generator — same element calls written against
  (a) the type-function surface (Lib.New<<C>> once per class at the top of the file),
  (c) the type-function surface instantiated inline at every call (L.New<<C>>("C")({...})),
  (b) the generated Declaration (D.<Class>({...})).
Props per call: Name + up to 3 boolean/number/string props of the class (from quad-roblox/dump/api-surface.json)
+ one event with `function() end` when the class has one + one Instance child.

  gen-cost.py <K classes> <M calls per class> <outdir> [--studio]
--studio writes the (b) variant with the ReplicatedStorage instance path (probe.project.json) instead of a
file-path require, and (a)/(c) with `require("./Lib")` (same in both).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../../.."))
SURF = json.load(open(os.path.join(ROOT, "quad-roblox/dump/api-surface.json")))["classes"]
SCOPE = ("Frame TextLabel TextButton ImageLabel ImageButton ScrollingFrame TextBox CanvasGroup ViewportFrame VideoFrame "
         "UICorner UIPadding UIStroke UIListLayout UIGridLayout UIScale UIGradient UIAspectRatioConstraint "
         "UISizeConstraint UITextSizeConstraint UIFlexItem UIPageLayout UITableLayout UIDragDetector UIShadow "
         "ScreenGui BillboardGui SurfaceGui Folder Camera WorldModel").split()
LIT = {"boolean": "true", "number": "1", "string": '"s"'}


def call_props(cls):
    c = SURF[cls]
    parts = ['Name = "n"']
    for p in c["props"]:
        if p["type"] in LIT and p["name"] != "Name":
            parts.append(f'{p["name"]} = {LIT[p["type"]]}')
        if len(parts) >= 4:
            break
    if c["events"]:
        e = c["events"][-1]
        args = ", ".join(f"_{i}" for i in range(len(e["params"])))
        parts.append(f'{e["name"]} = function({args}) end')
    parts.append('Instance.new("Folder")')
    return "{ " + ", ".join(parts) + " }"


def main():
    k, m, outdir = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    studio = "--studio" in sys.argv
    classes = SCOPE[:k]
    assert "Frame" in classes and "TextLabel" in classes, "negative controls need Frame and TextLabel (k >= 2)"
    os.makedirs(outdir, exist_ok=True)
    tag = f"k{k}m{m}"
    lib_req = 'require("./Lib")' if studio else f'require("{os.path.relpath(os.path.join(HERE, "../src/Lib"), outdir)}")'
    # (a) type-function surface, constructors hoisted
    a = ["--!strict", f"-- generated by harness/gen-cost.py {k} {m} — Q6 (a) type-function surface, constructors hoisted",
         f"local L = {lib_req}"]
    for c in classes:
        a.append(f'local {c}_ = L.New<<{c}>>("{c}")')
    out = []
    for c in classes:
        for i in range(m):
            a.append(f"local {c}_{i} = {c}_({call_props(c)})")
            out.append(f"{c}_{i}")
    # negative controls — must stay diagnosed (8.28: under too-complex, `D.TextLabel({ Text = 42 })` vanished)
    a.append('local BAD1 = Frame_({ Visible = 5 }) -- NEG')
    a.append('local BAD2 = TextLabel_({ Text = 42 }) -- NEG')
    a.append("return { BAD1, BAD2, " + ", ".join(out[:200]) + " }")
    # (c) inline instantiation per call
    cc = ["--!strict", f"-- generated by harness/gen-cost.py {k} {m} — Q6 (c) type-function surface, L.New<<C>> at every call",
          f"local L = {lib_req}"]
    for c in classes:
        for i in range(m):
            cc.append(f'local {c}_{i} = L.New<<{c}>>("{c}")({call_props(c)})')
    cc.append('local BAD1 = L.New<<Frame>>("Frame")({ Visible = 5 }) -- NEG')
    cc.append('local BAD2 = L.New<<TextLabel>>("TextLabel")({ Text = 42 }) -- NEG')
    cc.append("return { BAD1, BAD2, " + ", ".join(out[:200]) + " }")
    # (b) generated Declaration
    if studio:
        dreq = 'require(game:GetService("ReplicatedStorage")["quad-roblox"].src.Declaration)'
    else:
        dreq = f'require("{os.path.relpath(os.path.join(ROOT, "quad-roblox/src/Declaration"), outdir)}")'
    b = ["--!strict", f"-- generated by harness/gen-cost.py {k} {m} — Q6 (b) generated Declaration (5145-line module)",
         f"local DM = {dreq}", "local D: DM.Declaration = nil :: any"]
    for c in classes:
        for i in range(m):
            b.append(f"local {c}_{i} = D.{c}({call_props(c)})")
    b.append('local BAD1 = D.Frame({ Visible = 5 }) -- NEG')
    b.append('local BAD2 = D.TextLabel({ Text = 42 }) -- NEG')
    b.append("return { BAD1, BAD2, " + ", ".join(out[:200]) + " }")
    if studio:
        common = [
            "-- [P6] 비용 — 이 파일을 열고 빨간 줄·자동완성이 뜨기까지의 체감, 스크립트 분석 창의 \"too complex\" 여부,",
            "-- 맨 끝 NEG 두 줄(BAD1 `Visible = 5`, BAD2 `Text = 42`)에 빨간 줄이 실제로 뜨는가(8.28: too complex면 조용히 사라졌다).",
            "-- Studio(체감/too complex/NEG): ",
            "-- Vscode(체감/too complex/NEG): ",
        ]
        a[2:2] = common + ["-- CLI(harness/cost-run.py, k20m5 같은 크기): vsc·sync·pin 전부 NEG 2/2, too complex 0, 0.5~1.0s(대부분 defs 로드)."]
        cc[2:2] = common + ["-- CLI: NEG 2/2, too complex 0, 0.8s / 340 MiB. ⚠ 같은 꼴을 31×20=620 호출로 늘리면 too complex + 383 에러(1.7 GiB),",
                            "--   31×30=930이면 1313 에러(2.8 GiB) — 호출마다 L.New<<C>>를 새로 인스턴스화하는 꼴은 규모에 약하다(out/cost-cli.txt)."]
        b[2:2] = common + ["-- ⚠ Studio 전용(ReplicatedStorage 경로 require — VSCode에선 Unknown require). CLI 대응물은 harness가 만드는 cost-b 파일.",
                           "-- CLI(cost-b, 파일 경로 require): override 있는 vsc·pin은 NEG 2/2·too complex 0. **override 없는 sync(Roblox 동기 플래그 그대로)·",
                           "--   pinsync는 Declaration 모듈 안에서 too complex(6·2건)가 나고 NEG 0/2** — 하네스로 보면 D.Frame 자동완성 0개, hover *error-type*",
                           "--   (out/lsp-gend-compare.txt). 9/16 Studio는 too complex가 없었다 — 지금 D로 Studio가 여전히 그런지가 이 파일의 핵심 질문."]
    pre = "06" if studio else "cost"
    for name, lines in ((f"{pre}a-typefn-{tag}", a), (f"{pre}c-typefn-inline-{tag}", cc), (f"{pre}b-gend-{tag}", b)):
        with open(os.path.join(outdir, name + ".luau"), "w") as f:
            f.write("\n".join(lines) + "\n")
    print(f"wrote {pre}{{a,b,c}}-*-{tag}.luau in {outdir}")


if __name__ == "__main__":
    main()
