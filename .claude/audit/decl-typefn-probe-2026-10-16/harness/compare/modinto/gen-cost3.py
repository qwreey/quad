#!/usr/bin/env python3
"""[2026-10-19 M3 follow-up] cost files for Lib3 Modifier<C> in the kit's forms with an Into<GuiObject> prop
(adapted from harness/gen-modcost2.py, which is left untouched).
  gen-cost3.py <out-dir> <policy: full|t2|t3|t4|t7> <form: none|with|thinwith|tagfn> <N>
form none     no Into prop (control)
     with     Lib2 form IntoWith<GuiObject, Modifier<GuiObject>>, body `props.Modifier:AsGuiObject():AsTextButton()`
     thinwith (라) IntoThinWith, same body
     tagfn    side probe: tag-only Into + free conversion `ToGui(m)` in the body
Every fifth use is a GuiObject Modifier, and that one is also passed to Card. Two NEG lines at the end (`-- NEG`)."""
import os, sys
out, pol, form, n = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
P = {"full": "PolicyFull", "t2": "PolicyT2", "t3": "PolicyT3", "t4": "PolicyT4", "t7": "PolicyT7"}[pol]
os.makedirs(out, exist_ok=True)
L = ["--!strict", f"-- [2026-10-19 M3 follow-up cost] generated by modinto/gen-cost3.py {pol} {form} {n}",
     'local L = require("../../../../src/Lib3")',
     f"type P = L.{P}",
     "type CM<K> = index<L.ModClassMap, K>",
     "type EM<K> = index<L.CreatableMap, K>",
     "type Mod<C> = L.ModP<C, P>",
     "local Elem = (nil :: any) :: <K>(name: K & keyof<L.CreatableMap>) -> (L.Props<EM<K>>) -> EM<K>",
     "local Modifier = (nil :: any) :: <K>(name: K & keyof<L.ModClassMap>) -> (...any) -> Mod<CM<K>>",
     "local None = (nil :: any) :: L.None",
     'local Frame = Elem "Frame"', 'local TextButton = Elem "TextButton"', 'local TextLabel = Elem "TextLabel"', 'local TextBox = Elem "TextBox"',
     'local FrameModifier = Modifier "Frame"', 'local TextButtonModifier = Modifier "TextButton"',
     'local TextLabelModifier = Modifier "TextLabel"', 'local TextBoxModifier = Modifier "TextBox"', 'local GuiObjectModifier = Modifier "GuiObject"']
if form == "with":
    L += ["type CardProps = { read Modifier: L.IntoP<GuiObject, P>? }",
          "local function Card(props: CardProps) return TextButton { if props.Modifier then props.Modifier:AsGuiObject():AsTextButton() else None } end"]
elif form == "thinwith":
    L += ["type CardProps = { read Modifier: L.IntoThinWithP<GuiObject, P>? }",
          "local function Card(props: CardProps) return TextButton { if props.Modifier then props.Modifier:AsGuiObject():AsTextButton() else None } end"]
elif form == "tagfn":
    L += ['type CardProps = { read Modifier: { read __quadModifier: "GuiObject" | "GuiBase2d" | "GuiBase" | "Instance" }? }',
          'local ToGui = (nil :: any) :: (m: { read __quadModifier: "GuiObject" | "GuiBase2d" | "GuiBase" | "Instance" }) -> Mod<GuiObject>',
          "local function Card(props: CardProps) return TextButton { if props.Modifier then ToGui(props.Modifier):AsTextButton() else None } end"]
forms = [
    ('FrameModifier():Name("X{i}"):Size(UDim2.new(1, 0, 0, {i})):LayoutOrder({i})', "Frame"),
    ('TextButtonModifier():LayoutOrder({i}):Position(UDim2.fromOffset({i}, 0))', "TextButton"),
    ('TextLabelModifier():AutomaticSize(Enum.AutomaticSize.XY):TextSize({i}):TextWrapped(true)', "TextLabel"),
    ('TextBoxModifier():Name("F{i}"):TextXAlignment(Enum.TextXAlignment.Left)', "TextBox"),
    ('GuiObjectModifier():Size(UDim2.fromOffset({i}, 0)):AutomaticSize(Enum.AutomaticSize.Y)', "Frame"),
]
names = []
for i in range(n):
    f, el = forms[i % len(forms)]
    L.append(f"local m{i} = " + f.format(i=i))
    L.append(f"local e{i} = {el} {{ m{i}, BorderSizePixel = 0 }}")
    names += [f"m{i}", f"e{i}"]
    if form != "none" and i % len(forms) == 4:
        L.append(f"local k{i} = Card({{ Modifier = m{i} }})")
        names.append(f"k{i}")
L.append("local bad1 = FrameModifier():Size(5) -- NEG")
L.append("local bad2 = TextButton { FrameModifier() } -- NEG")
L.append("return { " + ", ".join(names[:150]) + ", bad1, bad2 }")
name = f"{pol}-{form}-{n:03d}.luau"
open(os.path.join(out, name), "w").write("\n".join(L) + "\n")
print(name)
