#!/usr/bin/env python3
"""[2026-10-19 M3 follow-up] one kit-form template, one file per (policy, Into form) variant — same line numbers in every file.
  gen-use.py            writes use-<variant>.luau next to this script
Variants: <policy>-<into>, policy in full|t2|t4|t7|t10|t13|t13n, into in
  with      Lib2 form       IntoWith<C, Modifier<C>>            (full As tree on the Into's copy)
  thin      (라) self-built  { read __quadModifier: tags, As<C>: (self: any) -> <copy built in its own call> }
  thinwith  (라) IntoThinWith<C, Modifier<C>>                    (tag + method returning the given Modifier)
  thinhand  (라) hand alias  { read __quadModifier: "GuiObject"|..., AsGuiObject: (self: any) -> Mod<GuiObject> }
  hand      gen-D shape     { AsGuiObject: (self: any) -> Mod<GuiObject> }   (no tag, alias return)
Suffix -direct: the per-class factories are spelled `(...any) -> Mod<Frame>` (class written directly) instead of the generic
`Modifier "Frame"` whose return is `Mod<index<ModClassMap, "Frame">>`.
Out-of-list markers (다) follow each policy's allow list."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
POL = {"full": "PolicyFull", "t2": "PolicyT2", "t2big": "PolicyT2big", "t3": "PolicyT3", "t4": "PolicyT4", "t5": "PolicyT5", "t6": "PolicyT6", "t7": "PolicyT7", "t10": "PolicyT10", "t13": "PolicyT13",
       "t13n": "PolicyT13n"}
ALLOW = {  # GuiObject targets; None = Lib2 full tree (every descendant, nested)
    "full": None,
    "t2": {"Frame", "TextButton"},
    "t2big": {"TextBox", "ScrollingFrame"},
    "t3": {"Frame", "TextButton", "TextLabel"},
    "t4": {"Frame", "TextButton", "TextLabel", "TextBox"},
    "t5": {"Frame", "TextButton", "TextLabel", "TextBox", "ImageButton"},
    "t6": {"Frame", "TextButton", "TextLabel", "TextBox", "ImageButton", "ImageLabel"},
    "t7": {"Frame", "TextButton", "TextLabel", "TextBox", "ImageButton", "ImageLabel", "ScrollingFrame"},
    "t10": {"Frame", "TextButton", "TextLabel", "TextBox", "ImageButton", "ImageLabel", "ScrollingFrame", "CanvasGroup",
            "VideoFrame", "ViewportFrame"},
    "t13": {"Frame", "TextButton", "TextLabel", "TextBox", "ImageButton", "ImageLabel", "ScrollingFrame", "CanvasGroup",
            "VideoFrame", "ViewportFrame", "GuiButton", "GuiLabel"},
}
ALLOW["t13n"] = ALLOW["t13"]
NESTED = {"full", "t13n"}  # GuiButton → TextButton second hop exists
INTO = {
    "with": "type IntoG = L.IntoP<GuiObject, P>",
    "thin": "type IntoG = L.IntoThinP<GuiObject, P>",
    "thinwith": "type IntoG = L.IntoThinWithP<GuiObject, P>",
    "thinhand": 'type IntoG = { read __quadModifier: "GuiObject" | "GuiBase2d" | "GuiBase" | "Instance", AsGuiObject: (self: any) -> Mod<GuiObject> }',
    "hand": "type IntoG = { AsGuiObject: (self: any) -> Mod<GuiObject> }",
}


def ok(cond):
    return "OK" if cond else "NEG"


def render(pol, into, fac="index"):
    a = ALLOW[pol]
    full = a is None
    has = (lambda c: full or c in a)
    thin = into.startswith("thin")
    L = [
        "--!strict",
        f"-- [2026-10-19 M3 follow-up] generated by modinto/gen-use.py — policy {pol}, Into form {into}, factory spelling {fac}. One-line -- NEG / -- OK markers.",
        'local L = require("../../../src/Lib3")',
        f"type P = L.{POL[pol]}",
        "type CM<K> = index<L.ModClassMap, K>",
        "type EM<K> = index<L.CreatableMap, K>",
        "type Mod<C> = L.ModP<C, P>",
        INTO[into],
        "local Elem = (nil :: any) :: <K>(name: K & keyof<L.CreatableMap>) -> (L.Props<EM<K>>) -> EM<K>",
        "local Modifier = (nil :: any) :: <K>(name: K & keyof<L.ModClassMap>) -> (...any) -> Mod<CM<K>>",
        "local None = (nil :: any) :: L.None",
        'local Frame = Elem "Frame"',
        'local TextButton = Elem "TextButton"',
        (f'local FrameModifier = Modifier "Frame"' if fac == 'index' else 'local FrameModifier = (nil :: any) :: (...any) -> Mod<Frame>'),
        (f'local TextButtonModifier = Modifier "TextButton"' if fac == 'index' else 'local TextButtonModifier = (nil :: any) :: (...any) -> Mod<TextButton>'),
        (f'local GuiObjectModifier = Modifier "GuiObject"' if fac == 'index' else 'local GuiObjectModifier = (nil :: any) :: (...any) -> Mod<GuiObject>'),
        (f'local GuiBase2dModifier = Modifier "GuiBase2d"' if fac == 'index' else 'local GuiBase2dModifier = (nil :: any) :: (...any) -> Mod<GuiBase2d>'),
        (f'local InstanceModifier = Modifier "Instance"' if fac == 'index' else 'local InstanceModifier = (nil :: any) :: (...any) -> Mod<Instance>'),
        (f'local ScreenGuiModifier = Modifier "ScreenGui"' if fac == 'index' else 'local ScreenGuiModifier = (nil :: any) :: (...any) -> Mod<ScreenGui>'),
        'local buttonName = TextButtonModifier():Name("Button") -- OK',
        "-- kit form (material Card.luau 81/214/237, List.luau 97/267/299)",
        "type CardProps = { read Modifier: IntoG?, read LayoutOrder: number? }",
        "local function Card(props: CardProps) return TextButton { if props.Modifier then props.Modifier:AsGuiObject():AsTextButton() else None } end -- OK",
        "local function CardF(props: CardProps) return Frame { if props.Modifier then props.Modifier:AsGuiObject():AsFrame() else None } end -- OK",
        "local function CardK(props: CardProps) return TextButton { buttonName, TextButtonModifier():Size(UDim2.new()), if props.Modifier then props.Modifier:AsGuiObject():AsTextButton() else None, BackgroundTransparency = 0, LayoutOrder = props.LayoutOrder } end -- OK kit-shaped element",
        "local function CardS(props: CardProps) return TextButton { if props.Modifier then props.Modifier:AsGuiObject():AsTextButton():AutoButtonColor(false):Text(\"x\") else None } end -- OK setters after the chain",
        "local function CardFS(props: CardProps) return Frame { if props.Modifier then props.Modifier:AsGuiObject():AsFrame():ClipsDescendants(true) else None } end -- OK",
        "local function surfaceSize() return GuiObjectModifier():Size(UDim2.fromOffset(240, 0)):AutomaticSize(Enum.AutomaticSize.Y) end",
        "local k1 = Card({ Modifier = surfaceSize() }) -- OK GuiObject modifier (helper return)",
        "local k2 = CardF({ Modifier = GuiObjectModifier() }) -- OK",
        "local k3 = Card({ Modifier = GuiBase2dModifier() }) -- OK ancestor GuiBase2d modifier",
        "local k4 = Card({ Modifier = InstanceModifier():Name(\"x\") }) -- OK ancestor Instance modifier",
        "local k5 = Card({ LayoutOrder = 1 }) -- OK no modifier",
        "local n1 = Card({ Modifier = FrameModifier() }) -- NEG descendant Frame modifier into Into<GuiObject>",
        "local n2 = Card({ Modifier = TextButtonModifier() }) -- NEG",
        "local n3 = Card({ Modifier = ScreenGuiModifier() }) -- NEG sibling branch (LayerCollector)",
        'local n4 = Card({ Modifier = Modifier "UIListLayout" () }) -- NEG unrelated class',
        "local function CardBad(props: CardProps) return Frame { if props.Modifier then props.Modifier:AsGuiObject():AsTextButton() else None } end -- NEG TextButton modifier into Frame",
        "local function CardBad2(props: CardProps) return TextButton { if props.Modifier then props.Modifier:AsGuiObject():AsTextButton():Size(5) else None } end -- NEG wrong setter value after the chain",
        "local function CardBad3(props: CardProps) return Frame { if props.Modifier then props.Modifier:AsGuiObject():AsFrame():Text(\"x\") else None } end -- NEG Frame has no Text",
        "-- plain assignments to the Into / identity across spellings",
        "local i1: IntoG = GuiObjectModifier() -- OK",
        "local i2: IntoG = InstanceModifier() -- OK ancestor",
        "local i3: IntoG = FrameModifier() -- NEG",
        "local i4: Mod<GuiObject> = GuiObjectModifier() -- OK cross spelling (Lib2 into-ident x1 was too complex in sync)",
        "local i5: Mod<TextButton> = GuiObjectModifier():AsTextButton() -- OK",
        "-- leaf / out-of-list down-casts (다)",
        "local l1 = FrameModifier():AsTextButton() -- NEG leaf has no down-cast",
        "local l2 = TextButtonModifier():AsGuiObject() -- NEG no checked up-cast",
        f'local o1 = GuiObjectModifier():AsTextLabel():Text("x") -- {ok(has("TextLabel"))} list: TextLabel',
        f"local o2 = GuiObjectModifier():AsScrollingFrame():CanvasSize(UDim2.new()) -- {ok(has('ScrollingFrame'))} list: ScrollingFrame",
        f"local o3 = GuiObjectModifier():AsViewportFrame() -- {ok(has('ViewportFrame'))} list: ViewportFrame",
        f"local o4 = GuiObjectModifier():AsGuiButton():AsTextButton() -- {ok(pol in NESTED)} list: GuiButton second hop",
        "local o5 = InstanceModifier():AsGuiObject():AsFrame() -- OK ancestor → GuiObject → Frame",
        f"local o6 = InstanceModifier():AsFrame() -- {ok(full)} list: Instance → Frame direct",
        f"local o7 = GuiBase2dModifier():AsTextButton() -- {ok(full)} list: GuiBase2d → TextButton direct",
        "-- placement sanity",
        "local p1 = Frame { GuiObjectModifier(), FrameModifier(), InstanceModifier() } -- OK own + ancestor tags",
        "local p2 = TextButton { FrameModifier() } -- NEG sibling class",
        "local d1 = TextButton { GuiObjectModifier():AsTextButton():Text(\"x\") } -- OK",
        "local d2 = Frame { GuiObjectModifier():AsTextButton() } -- NEG",
        "-- custom Into implementation (no tag): thin forms reject it by construction — counted separately (SEMANTIC)",
        "local custom = { AsGuiObject = function(self: any) return GuiObjectModifier() end }",
        f"local c1 = Card({{ Modifier = custom }}) -- SEMANTIC custom Into ({'tag required' if thin else 'accepted in gen D'})",
        "-- LSP probes",
        "local hv = GuiObjectModifier():Size(UDim2.new()) -- @h(gm-value) at='hv =' -- @c(gm-dot) at='GuiObjectModifier():' ins='A' -- OK",
        "local function Probe(props: CardProps) local x = props.Modifier and props.Modifier:AsGuiObject() return x end -- @c(into-dot) at='props.Modifier and props.Modifier:' ins='A' -- @h(into-prop) at='props: CardProps' -- OK",
        "local function Probe2(props: CardProps) local y = props.Modifier and props.Modifier:AsGuiObject():AsTextButton() return y end -- @c(as-dot) at='props.Modifier:AsGuiObject():' ins='A' -- OK",
        "return { buttonName, Card, CardF, CardK, CardS, CardFS, k1, k2, k3, k4, k5, n1, n2, n3, n4, CardBad, CardBad2, CardBad3, i1, i2, i3, i4, i5,",
        "\tl1, l2, o1, o2, o3, o4, o5, o6, o7, p1, p2, d1, d2, c1, hv, Probe, Probe2 }",
    ]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    combos = [(p, "with") for p in POL] + [("full", i) for i in ("thin", "thinwith", "thinhand", "hand")] \
        + [(p, i) for p in ("t2", "t7", "t13n") for i in ("thinwith", "thinhand")]
    for p, i in combos:
        name = f"use-{p}-{i}.luau"
        open(os.path.join(HERE, name), "w").write(render(p, i))
        print(name)
    # factory spelled with the class directly (`(...any) -> Mod<GuiObject>`) instead of `Mod<index<ModClassMap, K>>`
    for p, i in [(p, "with") for p in POL] + [("full", "hand"), ("full", "thinwith"), ("full", "thinhand")]:
        name = f"use-{p}-{i}-direct.luau"
        open(os.path.join(HERE, name), "w").write(render(p, i, "direct"))
        print(name)
