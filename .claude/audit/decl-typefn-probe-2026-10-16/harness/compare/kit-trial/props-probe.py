#!/usr/bin/env python3
"""[2026-10-20 kit trial] field-level probe of every INPUT Modifier prop the codemod rewrote.
  props-probe.py <variant-root> <base|new> <codemod-report.json> <kit>
For each exported table type whose field got `ModifierInto<C>` (new) / was `<C>Modifier`·`Into<C>` (base), write into
<kit>/src/ZzPropsProbe.luau three one-line cases against `index<M.T, "F">` (the field type alone, nothing else of the props):
  same class Modifier            -- OK
  ancestor class Modifier        -- ANC   (new marker: accepted by design; base full type: ?)
  sibling / unrelated class      -- NEG   (round 2 "b2": the full generated type let these through)
"""
import json, os, re, sys
root, variant, repf, kit = sys.argv[1:]
reps = json.load(open(repf))
SIB = {"Frame": "TextLabel", "TextLabel": "Frame", "TextButton": "Frame", "TextBox": "Frame", "ImageLabel": "Frame",
       "ImageButton": "Frame", "ScrollingFrame": "Frame", "CanvasGroup": "Frame", "ScreenGui": "Frame",
       "GuiObject": "UIListLayout", "GuiButton": "Frame"}
ANC = {"GuiObject": "Instance", "ScreenGui": "LayerCollector"}
entries = []
for r in reps:
    if not r["file"].startswith(kit + "/") or r.get("setup"):
        continue
    # original line numbers (the report) index the UNCONVERTED file — the header shifts the new one
    newsrc = open(os.path.join(os.path.dirname(os.path.abspath(repf)), "..", "base", r["file"])).read().split("\n") if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(repf)), "..", "base", r["file"])) else open(os.path.join(root, r["file"])).read().split("\n")
    for ln, old, new, kind, field in r.get("types", []):
        if kind != "input" or "ModifierInto" not in new:
            continue
        cls = re.search(r"<(\w+)>", new).group(1)
        # enclosing exported type: nearest `export type X = {` above (no closing `}` at column 0 in between)
        tname = None
        for i in range(ln - 1, -1, -1):
            l = newsrc[i]
            m = re.match(r"export type (\w+)\s*=\s*\{", l)
            if m:
                tname = m.group(1)
                break
            if re.match(r"^\}", l) or re.match(r"^(local |function |return )", l):
                break
        if tname is None:
            continue
        entries.append((r["file"], tname, field, cls))
mods = {}
lines = ["--!strict", f"-- [kit trial props probe — {variant}] generated by props-probe.py; one-line markers"]
q = 'local q = require("./Quad")'
lines.append(q)
used = sorted({c for _, _, _, c in entries} | {SIB.get(c, "Frame") for _, _, _, c in entries} | {ANC.get(c, "GuiObject") for _, _, _, c in entries})
if variant == "new":
    for c in used:
        lines.append(f'local {c}Modifier = q.Modifier "{c}"')
    mk = lambda c: f"{c}Modifier()"
else:
    lines.append("local D = q.Declaration")
    mk = lambda c: f"D.Modifier.{c}()"
seen = set()
body = []
for i, (f, t, fld, c) in enumerate(entries):
    if (f, t, fld) in seen:
        continue
    seen.add((f, t, fld))
    rel = os.path.relpath(os.path.join(root, f), os.path.join(root, kit, "src"))
    rel = re.sub(r"\.luau$", "", rel)
    rel = re.sub(r"/init$", "", rel)
    if not rel.startswith("."):
        rel = "./" + rel
    if rel not in mods:
        mods[rel] = f"M{len(mods)}"
        lines.append(f'local {mods[rel]} = require("{rel}")')
    m = mods[rel]
    body.append(f'local ok{i}: index<{m}.{t}, "{fld}"> = {mk(c)} -- OK {f} {t}.{fld} <{c}>')
    body.append(f'local anc{i}: index<{m}.{t}, "{fld}"> = {mk(ANC.get(c, "GuiObject"))} -- ANC {f} {t}.{fld} <{c}>')
    body.append(f'local neg{i}: index<{m}.{t}, "{fld}"> = {mk(SIB.get(c, "Frame"))} -- NEG {f} {t}.{fld} <{c}>')
lines += body
lines.append("return {}")
out = os.path.join(root, kit, "src", "ZzPropsProbe.luau")
open(out, "w").write("\n".join(lines) + "\n")
print(f"{variant} {kit}: {len(seen)} fields in {len(mods)} modules → {out}")
