#!/usr/bin/env python3
"""[2026-10-19 M4] the class-name bound crossing a module boundary: module `names-N.luau` exports Map + Names (literal union),
consumer `use-<kind>-N.luau` requires it and builds the Elem-shaped factory (kind = lit: `K & M.Names`, keyof: `K & keyof<M.Map>`,
fac: the factory itself is exported by the module (`M.Elem`) — the shape q.Elem would have)."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "../src/FullMaps.luau")).read()
body = src.split("export type CreatableMapFull = {")[1].split("}")[0]
names = re.findall(r"^\t(\w+): \w+,", body, re.M)
gui31 = ["BillboardGui", "Camera", "CanvasGroup", "Folder", "Frame", "ImageButton", "ImageLabel", "ScreenGui", "ScrollingFrame", "SurfaceGui",
         "TextBox", "TextButton", "TextLabel", "UIAspectRatioConstraint", "UICorner", "UIDragDetector", "UIFlexItem", "UIGradient", "UIGridLayout",
         "UIListLayout", "UIPadding", "UIPageLayout", "UIScale", "UIShadow", "UISizeConstraint", "UIStroke", "UITableLayout",
         "UITextSizeConstraint", "VideoFrame", "ViewportFrame", "WorldModel"]
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
for n in map(int, sys.argv[2:]):
    base = ["Part", "Sound", "Model"] + gui31
    cls = base + [c for c in names if c not in base][: max(0, n - len(base))]
    N = f"{len(cls):03d}"
    mod = ["--!strict", f"-- [2026-10-19 M4] generated by harness/gen-mapsize3.py — {len(cls)} classes", 'local L = require("../../../src/Lib2")',
           "export type Map = { " + ", ".join(f"{c}: {c}" for c in cls) + " }",
           "export type Names = " + " | ".join(f'"{c}"' for c in cls),
           "export type ElemFn = <K>(name: K & Names) -> (L.Props<index<Map, K>>) -> index<Map, K>",
           "return { Elem = (nil :: any) :: ElemFn }"]
    open(os.path.join(out, f"names-{N}.luau"), "w").write("\n".join(mod) + "\n")
    for kind, sig in (("lit", "<K>(name: K & M.Names) -> (L.Props<index<M.Map, K>>) -> index<M.Map, K>"),
                      ("keyof", "<K>(name: K & keyof<M.Map>) -> (L.Props<index<M.Map, K>>) -> index<M.Map, K>"),
                      ("fac", None)):
        L = ["--!strict", f"-- [2026-10-19 M4] generated by harness/gen-mapsize3.py — consumer of names-{N}, {kind}",
             'local L = require("../../../src/Lib2")', f'local M = require("./names-{N}")',
             (f"local E = (nil :: any) :: {sig}" if sig else "local E = M.Elem"),
             'local Part = E "Part"', 'local Frame = E "Frame"', 'local TextLabel = E "TextLabel"',
             "local ok1 = Frame { Visible = true }", "local bad1 = Frame { Visible = 5 } -- NEG", 'local bad2 = E "Prt" -- NEG',
             "return { Part, TextLabel, ok1, bad1, bad2 }"]
        open(os.path.join(out, f"use-{kind}-{N}.luau"), "w").write("\n".join(L) + "\n")
