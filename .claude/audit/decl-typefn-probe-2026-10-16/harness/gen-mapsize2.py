#!/usr/bin/env python3
"""[2026-10-19 M4] like gen-mapsize.py but the factory returns a CONSTRUCTOR `(L.Props<index<Map, K>>) -> index<Map, K>` (the Elem shape).
  gen-mapsize2.py <out-dir> <N...>   variants: keyof (`K & keyof<Map>`), lit (`K & Names` literal union), and
  litmap (literal union bound, constructor type looked up from a precomputed name->ctor map type is NOT possible —
  skipped). 3 hoists + 2 NEG."""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "../src/FullMaps.luau")).read()
body = src.split("export type CreatableMapFull = {")[1].split("}")[0]
names = re.findall(r"^\t(\w+): \w+,", body, re.M)
must = ["Part", "Frame", "TextLabel", "Sound", "Model"]
gui31 = ["BillboardGui", "Camera", "CanvasGroup", "Folder", "Frame", "ImageButton", "ImageLabel", "ScreenGui", "ScrollingFrame", "SurfaceGui",
         "TextBox", "TextButton", "TextLabel", "UIAspectRatioConstraint", "UICorner", "UIDragDetector", "UIFlexItem", "UIGradient", "UIGridLayout",
         "UIListLayout", "UIPadding", "UIPageLayout", "UIScale", "UIShadow", "UISizeConstraint", "UIStroke", "UITableLayout",
         "UITextSizeConstraint", "VideoFrame", "ViewportFrame", "WorldModel"]
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
for n in map(int, sys.argv[2:]):
    base = ["Part", "Sound", "Model"] + gui31
    cls = base + [c for c in names if c not in base][: max(0, n - len(base))]
    m = "type Map = { " + ", ".join(f"{c}: {c}" for c in cls) + " }"
    u = "type Names = " + " | ".join(f'"{c}"' for c in cls)
    for kind, bound in (("keyof", "keyof<Map>"), ("lit", "Names")):
        L = ["--!strict", f"-- [2026-10-19 M4] generated by harness/gen-mapsize2.py — {len(cls)} classes, {kind} bound, Elem-shaped return",
             'local L = require("../../../src/Lib2")', m, u,
             f"local E = (nil :: any) :: <K>(name: K & {bound}) -> (L.Props<index<Map, K>>) -> index<Map, K>",
             'local Part = E "Part"', 'local Frame = E "Frame"', 'local TextLabel = E "TextLabel"',
             "local ok1 = Frame { Visible = true }",
             "local bad1 = Frame { Visible = 5 } -- NEG",
             'local bad2 = E "Prt" -- NEG',
             "return { Part, TextLabel, ok1, bad1, bad2 }"]
        open(os.path.join(out, f"{kind}-{len(cls):03d}.luau"), "w").write("\n".join(L) + "\n")
