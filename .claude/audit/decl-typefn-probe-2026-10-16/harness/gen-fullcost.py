#!/usr/bin/env python3
"""[2026-10-19 M4] hoisted-constructor cost: 5 hoists at the top, N uses below, 2 NEG at the end.
  gen-fullcost.py <out-dir> <variant> <N>
variants: map31 (Lib2 31 CreatableMap + Lib2 Policy), full (src/FullMapsKeep 361 map, keyof bound, FullPolicy),
          fulllit (same, literal-union bound), fullnongui (full map, non-GUI classes Part/Model/Sound/Attachment/PointLight)."""
import os, sys
out, variant, n = sys.argv[1], sys.argv[2], int(sys.argv[3])
os.makedirs(out, exist_ok=True)
gui = [("Frame", "Visible = true, Size = UDim2.new(0, {i}, 0, 10)"), ("TextLabel", 'Text = "t{i}", TextSize = {i}'),
       ("TextButton", "AutoButtonColor = false, LayoutOrder = {i}"), ("ImageLabel", 'Image = "rbxassetid://{i}"'),
       ("ScrollingFrame", "CanvasSize = UDim2.new(0, 0, 0, {i})")]
nongui = [("Part", "Anchored = true, Size = Vector3.new({i}, 1, 1)"), ("Model", 'Name = "m{i}"'), ("Sound", "Volume = 0.{i}"),
          ("Attachment", "Position = Vector3.new({i}, 0, 0)"), ("PointLight", "Brightness = {i}")]
L = ["--!strict", f"-- [2026-10-19 M4 cost] generated by harness/gen-fullcost.py {variant} {n}", 'local L = require("../../../src/Lib2")']
if variant == "map31":
    L += ["type EM<K> = index<L.CreatableMap, K>", "local Elem = (nil :: any) :: <K>(name: K & keyof<L.CreatableMap>) -> (L.Props<EM<K>>) -> EM<K>"]
    classes = gui
else:
    bound = "F.CreatableNamesFull" if variant == "fulllit" else "keyof<F.CreatableMapFull>"
    L += ['local F = require("../../../src/FullMapsKeep")', "type EM<K> = index<F.CreatableMapFull, K>",
          f"local Elem = (nil :: any) :: <K>(name: K & {bound}) -> (F.FProps<EM<K>>) -> EM<K>"]
    classes = nongui if variant == "fullnongui" else gui
for c, _ in classes:
    L.append(f'local {c} = Elem "{c}"')
names = []
for i in range(n):
    c, p = classes[i % len(classes)]
    L.append(f"local u{i} = {c} {{ {p.format(i=i)} }}")
    names.append(f"u{i}")
c0, _ = classes[0]
L.append(f"local bad1 = {c0} {{ Name = 5 }} -- NEG")
L.append('local bad2 = Elem "Prt" -- NEG')
L.append("return { " + ", ".join(names[:100]) + ", bad1, bad2 }")
open(os.path.join(out, f"{variant}-{n:03d}.luau"), "w").write("\n".join(L) + "\n")
