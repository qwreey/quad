#!/usr/bin/env python3
"""[2026-10-20 3.4.0 unit 0] Generate a large mixed consumer file over Ext5 (hoisted Elem/Modifier/Spread/OnEvent/OnChange/Out,
Spread:Append(SpreadInto), Modifier setter chains) with planted NEG lines at the END (where a checker that gave up loses them).
  gen-bigmix.py <blocks> -> harness/compare/bigmix/mix-<blocks>.luau"""
import sys, pathlib
n = int(sys.argv[1])
out = pathlib.Path(__file__).parent / "compare" / "bigmix" / f"mix-{n}.luau"
L = ['--!strict', f'-- [generated by harness/gen-bigmix.py {n}]', 'local E = require("./Ext5")', 'local q: E.Q = (nil :: any)',
     'local Frame = q.Elem "Frame"', 'local TextLabel = q.Elem "TextLabel"', 'local TextButton = q.Elem "TextButton"',
     'local ImageLabel = q.Elem "ImageLabel"', 'local ScrollingFrame = q.Elem "ScrollingFrame"', 'local UIListLayout = q.Elem "UIListLayout"',
     'local FrameModifier = q.Modifier "Frame"', 'local GuiModifier = q.Modifier "GuiObject"', 'local LabelModifier = q.Modifier "TextLabel"',
     'local FrameSpread = q.Spread "Frame"', 'local GuiSpread = q.Spread "GuiObject"', 'local ButtonSpread = q.Spread "TextButton"',
     'local GuiOnEvent = q.OnEvent "GuiObject"', 'local FrameOnEvent = q.OnEvent "Frame"', 'local ButtonOnEvent = q.OnEvent "TextButton"',
     'local FrameOnChange = q.OnChange "Frame"', 'local ScrollOut = q.Out "ScrollingFrame"', '']
for i in range(n):
    L += [
        f'local function Hover{i}(onEnter: () -> ()): E.Spread<GuiObject>',
        f'\treturn GuiSpread {{ BackgroundTransparency = 0.5, GuiOnEvent "MouseEnter" (function(x, y) local _n: number = x + y; onEnter() end) }}',
        'end',
        f'local function Card{i}(title: string, canvas: any)',
        f'\tlocal hooks = FrameSpread {{ Visible = true, LayoutOrder = {i} }}',
        f'\thooks:Append(Hover{i}(function() end))',
        f'\thooks:Append(GuiSpread {{ ZIndex = {i % 7 + 1} }})',
        f'\tlocal m = FrameModifier():BackgroundTransparency(0.1):Size(UDim2.fromOffset({i}, {i}))',
        '\treturn Frame {',
        '\t\tm, hooks,',
        '\t\tFrameOnEvent "MouseLeave" (function(x, y) local _n: number = x end),',
        '\t\tFrameOnChange "AbsoluteSize" (function(v) local _w: number = v.X end),',
        f'\t\tTextLabel {{ Text = title, TextSize = {10 + i % 9}, LabelModifier():TextWrapped(true), GuiModifier() }},',
        f'\t\tTextButton {{ Text = "ok{i}", ButtonSpread {{ AutoButtonColor = false }}, ButtonOnEvent "Activated" (function(input, count) local _c: number = count end) }},',
        f'\t\tImageLabel {{ Image = "rbxassetid://{i}", ImageTransparency = 0.2 }},',
        '\t\tScrollingFrame { ScrollOut "CanvasSize" (canvas), UIListLayout { Padding = UDim.new(0, 4) } },',
        '\t}',
        'end',
        '',
    ]
NEG = [
    'local _neg1 = Frame { Visible = 5 } -- NEG value',
    'local _neg2 = FrameSpread { Visible = "x" } -- NEG spread value',
    'local _negs = FrameSpread {}; _negs:Append(ButtonSpread {}) -- NEG sibling spread into Append',
    'local _neg4 = FrameOnEvent "MouseEnterr" (function() end) -- NEG event name',
    'local _neg5 = FrameOnChange "AbsoluteSize" (function(v) local _s: string = v end) -- NEG callback type',
    'local _neg6 = ScrollOut "CanvasSize" (q.Source(5)) -- NEG Out source type',
    'local _neg7 = FrameModifier():Visible(5) -- NEG modifier setter value',
    'local _neg8 = TextLabel { ButtonSpread {} } -- NEG sibling spread on element',
]
L += NEG
out.write_text("\n".join(L) + "\n")
print(out, len(L), "lines")
