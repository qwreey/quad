#!/usr/bin/env python3
"""Generate `reflection.luau` (class -> writable props / events) for the Lune test harness.

Source: `quad-roblox/dump/api-surface.json` (the same dump `scripts/gen-d.py` reads), so the
mock ReflectionService answers exactly what the generated Declaration exposes. Re-run when the
dump changes: `python3 test/support/gen-reflection.py` from the kit folder.
"""
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, "..", "..", ".."))
dump = json.load(open(os.path.join(repo, "quad-roblox", "dump", "api-surface.json")))
out = ["-- GENERATED by test/support/gen-reflection.py from quad-roblox/dump/api-surface.json - do not edit", "return {"]
for cls in sorted(dump["classes"]):
    c = dump["classes"][cls]
    props = sorted({p["name"] for p in c["props"]})
    events = sorted({e["name"] for e in c["events"]})
    out.append(f"\t{cls} = {{")
    out.append("\t\tprops = { " + ", ".join(f'"{p}"' for p in props) + " },")
    out.append("\t\tevents = { " + ", ".join(f'"{e}"' for e in events) + " },")
    out.append("\t},")
out.append("}")
open(os.path.join(here, "reflection.luau"), "w").write("\n".join(out) + "\n")
print(f"reflection.luau: {len(dump['classes'])} classes")
